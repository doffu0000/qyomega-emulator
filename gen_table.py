"""Generate decode_table.go from MAME's h8s2600d.inc (BSD-3-Clause, Olivier Galibert)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, "..", "re", "mame_h8", "h8s2600d.inc")
HDR = os.path.join(HERE, "..", "re", "mame_h8", "h8d.h")
enum = re.search(r"enum \{(.*?)\};", open(HDR).read(), re.S).group(1)
ams = re.findall(r"DASM_(\w+)", enum)
ENTRY = re.compile(r'\{\s*(\d+),\s*0x([0-9a-f]+),\s*0x([0-9a-f]+),\s*0x([0-9a-f]+),\s*0x([0-9a-f]+),'
                   r'\s*"([^"]+)",\s*(?:DASM_(\w+)|0),\s*(?:DASM_(\w+)|0),\s*(\d+)([^}]*)\}')
out = ["// Code generated by gen_table.py from MAME h8s2600d.inc. DO NOT EDIT.", "// Derived from the H8S disassembler tables of MAME, BSD-3-Clause, Copyright (c) Olivier Galibert and the", "// MAME team (full licence text in NOTICE.md). SPDX-License-Identifier: BSD-3-Clause AND GPL-3.0-only.", "package main", "",
       "const ("]
for i, a in enumerate(ams):
    out.append("\tam_%s = %d" % (a, i))
out += [")", "", "var amNames = []string{" + ", ".join('"%s"' % a for a in ams) + "}", "",
        "var decodeTable = []insEntry{"]
n = 0
for line in open(INC):
    m = ENTRY.search(line)
    if m:
        slot, val, mask, val0, mask0, name, am1, am2, size, flags = m.groups()
        out.append('\t{%s, 0x%s, 0x%s, 0x%s, 0x%s, "%s", am_%s, am_%s, %s},' % (
            slot, val, mask, val0, mask0, name, am1 or "none", am2 or "none", size))
        n += 1
out.append("}")
open(os.path.join(HERE, "decode_table.go"), "w").write("\n".join(out) + "\n")
print(n, "entries,", len(ams), "operand kinds")
